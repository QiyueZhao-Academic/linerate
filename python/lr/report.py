def build_macros(data: dict, figure_facts: dict) -> Macros:
    m = Macros()
    env = data.get("environment", {})

    # Environment
    m.text("envCPU", env.get("cpu_model", "unknown"))
    m.text("envArch", env.get("arch", "unknown"))
    m.text("envOS", env.get("os", "unknown"))
    m.text("envCompiler", env.get("compiler", "unknown"))
    m.text("envOpenSSL", env.get("openssl_version", "unknown"))
    m.text("envHostClass", env.get("host_class", "unknown"))
    m.text("envIsolationTier", env.get("isolation_tier", "unknown"))
    m.text("envNICDriver", env.get("nic_driver", "unknown"))
    m.text("envGitCommit", env.get("git_commit", "unversioned"))
    m.num("envCores", env.get("physical_cores"))
    m.num("envTSCGHz", (env.get("tsc_hz") or 0) / 1e9, 3)
    m.num("envReplicates", env.get("run", {}).get("replicates"))
    m.pct("envCVThreshold", env.get("run", {}).get("cv_threshold", 0.0), 0)

    # Protocol constants, so the text can never quote a stale header size.
    proto = env.get("protocol", {})
    m.num("protoHeaderBytes", proto.get("header_bytes"))
    m.num("protoTagBytes", proto.get("tag_bytes"))
    m.num("protoMaxPayload", proto.get("max_payload_bytes"))
    m.num("protoMTU", proto.get("mtu_bytes"))
    m.num("protoIPUDPOverhead", proto.get("ip_udp_overhead_bytes"))

    # E1: one set of macros per cipher and hardware level, plus the headline.
    pts = data.get("e1", {}).get("points", [])
    best_hw = None
    for cipher in sorted({p["cipher"] for p in pts}):
        tag = cipher_tag(cipher)
        for hw in (True, False):
            if not any(p["cipher"] == cipher and bool(p["hw_crypto"]) == hw for p in pts):
                continue
            f = model.fit_from_points(pts, cipher, hw)
            suffix = "Hw" if hw else "Masked"
            m.num(f"fitA{tag}{suffix}", f.a if f.ok else None)
            m.num(f"fitB{tag}{suffix}", f.b if f.ok else None, 3)
            m.num(f"fitSStar{tag}{suffix}", f.s_star if f.ok else None)
            m.num(f"fitSStarLo{tag}{suffix}", f.s_star_ci[0] if f.ok else None)
            m.num(f"fitSStarHi{tag}{suffix}", f.s_star_ci[1] if f.ok else None)
            m.num(f"fitRsq{tag}{suffix}", f.r_squared if f.ok else None, 4)
            m.num(f"fitN{tag}{suffix}", f.n if f.ok else None)
            m.text(f"fitCurvature{tag}{suffix}", f.curvature_note or "not evaluated")
            if hw and f.ok and (best_hw is None or f.a < best_hw[1].a):
                best_hw = (cipher, f)

    if best_hw:
        m.text("bestCipher", best_hw[0])
        m.num("bestA", best_hw[1].a)
        m.num("bestB", best_hw[1].b, 3)
        m.num("bestSStar", best_hw[1].s_star)
    else:
        for name in ("bestA", "bestB", "bestSStar"):
            m.set(name, MISSING)
        m.set("bestCipher", MISSING)

    e1 = data.get("e1", {})
    m.pct("anchorDrift", e1.get("anchor_drift"), 2)
    m.text("anchorVerdict", "valid" if e1.get("anchor_ok") else "void")
    m.num("eOneUnits", len(pts))

    # The comparison the report leads on: our implementation against OpenSSL's.
    def _fit(c, hw=True):
        return model.fit_from_points(pts, c, hw) if pts else None
    ours, theirs = _fit("lr-aes-256-gcm"), _fit("aes-256-gcm")
    if ours and theirs and ours.ok and theirs.ok and theirs.b > 0:
        m.num("simdVsOpensslB", ours.b / theirs.b, 2)
        m.num("simdVsOpensslA", ours.a / theirs.a if theirs.a else None, 2)
    else:
        m.set("simdVsOpensslB", MISSING)
        m.set("simdVsOpensslA", MISSING)

    # E2
    e2 = data.get("e2", {})
    sc = figure_facts.get("scaling", {})
    m.num("scaleMaxShards", sc.get("max_shards", e2.get("max_shards")))
    m.num("scaleSerialFraction", sc.get("serial_fraction"), 4)
    m.text("scalePool", e2.get("pool", "unknown"))
    e2m = data.get("e2_mpi", {})
    m.num("mpiRanks", e2m.get("ranks") if e2m.get("available") else None)
    m.num("mpiHosts", e2m.get("distinct_hosts") if e2m.get("available") else None)
    m.num("mpiCoordNs", e2m.get("coordination_ns_per_iteration")
          if e2m.get("available") else None, 0)

    # E3
    e3 = data.get("e3", {})
    m.num("ioPosixCycles", e3.get("posix_b1_cycles"))
    m.num("ioSqpollCycles", e3.get("sqpoll_b1_cycles"))
    m.num("ioBoundaryCycles", e3.get("posix_minus_sqpoll_b1_cycles"))
    m.text("ioSqpollNote", e3.get("sqpoll_interpretation", "not evaluated"))
    m.text("ioBestBatched", e3.get("best_batched_backend", "none"))
    m.num("ioBestBatchedCycles", e3.get("best_batched_cycles"))

    # E4
    e4 = data.get("e4", {})
    m.num("memSustainedGBps", e4.get("stream_bandwidth_gbps"), 1)
    m.num("memRoofGBps", e4.get("roof_payload_gbps"), 2)
    m.num("memPasses", e4.get("payload_passes_total"))

    # E5
    e5 = data.get("e5", {})
    m.num("latCapacityPPS", e5.get("capacity_pps"))
    m.num("latKneePPS", e5.get("knee_pps"))
    m.pct("latKneeFraction", e5.get("knee_fraction"))
    m.text("latTopology", e5.get("topology", "unknown"))
    m.text("latNetem", e5.get("netem_label", "none"))
    m.text("latInterpretation", e5.get("interpretation_note", "not evaluated"))

    # E6
    e6 = data.get("e6", {})
    ossl = next((r for r in e6.get("openssl_speed", []) if r.get("ok")), None)
    m.num("refOpensslCycPerByte", ossl.get("cycles_per_byte") if ossl else None, 4)
    lr0 = next(iter(e6.get("linerate", [])), None)
    m.num("refOursCycPerByte", lr0.get("cycles_per_byte_per_pass") if lr0 else None, 4)
    net = data.get("e6_network", {})
    m.num("refIperfGbps", net.get("iperf3_gbps"), 2)
    m.num("refWireGuardGbps", net.get("wireguard_gbps"), 2)
    m.num("refLinerateGbps", net.get("linerate_gbps"), 2)

    # E7
    e7 = data.get("e7", {})
    m.num("virtTiers", e7.get("tiers_measured"))
    m.num("virtChainPerHop", e7.get("chain_cycles_per_hop"))
    tiers = {t["tier"]: t for t in e7.get("tiers", []) if t.get("ok")}
    for tier in ("host", "netns", "container", "gvisor"):
        t = tiers.get(tier)
        name = tier.capitalize()
        m.num(f"virt{name}Cycles", t.get("cycles_median") if t else None)
        m.num(f"virt{name}Relative", t.get("relative_to_host") if t else None, 3)

    # E8
    e8 = data.get("e8", {})
    if e8.get("available"):
        m.text("gpuDevice", e8.get("device", "unknown"))
        m.num("gpuLaunchNs", e8.get("launch_fixed_ns"), 0)
        m.num("gpuMarginalNs", e8.get("marginal_ns_per_packet"), 3)
        m.num("gpuWorthwhileBatch", e8.get("worthwhile_batch_packets"))
    else:
        m.set("gpuDevice", MISSING)
        for n in ("gpuLaunchNs", "gpuMarginalNs", "gpuWorthwhileBatch"):
            m.set(n, MISSING)

    # E9
    e9 = data.get("e9", {})
    if e9.get("available"):
        m.num("mlSamples", e9.get("n_samples"))
        m.num("mlTestRSquared", e9.get("test_r2"), 3)
        m.num("mlBaselineRSquared", e9.get("baseline_r2"), 3)
        m.pct("mlAdmissionGain", e9.get("admission_gain"))
        m.text("mlBestModel", e9.get("best_model", "unknown"))
    else:
        for n in ("mlSamples", "mlTestRSquared", "mlBaselineRSquared", "mlAdmissionGain"):
            m.set(n, MISSING)
        m.set("mlBestModel", MISSING)

    # Controls
    ctl = data.get("controls", {})
    m.num("ctlRan", ctl.get("ran"))
    m.num("ctlPassed", ctl.get("passed"))
    m.num("ctlNullFixed", ctl.get("null_fixed_cycles"))
    m.num("ctlAEADOnlyFixed", ctl.get("aead_only_fixed_cycles"))
    m.num("ctlAEADFixed", ctl.get("aead_fixed_cycles"))
    m.text("ctlPerByteIdentifiable",
           "yes" if ctl.get("per_byte_identifiable") else "no")
    m.num("ctlAnchorReplicates", data.get("e1", {}).get("anchor_replicates"))

    # Provenance
    prov = data.get("provenance", {})
    m.num("provFragments", len(prov.get("fragments_present", [])))
    m.text("provMissing", ", ".join(prov.get("fragments_missing", [])) or "none")
    return m


def build(data: dict, figure_facts: dict) -> dict[str, str]:
    """Return the generated files, keyed by filename."""
    out = {"macros.tex": build_macros(data, figure_facts).render()}
    for name, fn in TABLES.items():
        try:
            out[f"table_{name}.tex"] = fn(data)
        except Exception as exc:                      # noqa: BLE001
            out[f"table_{name}.tex"] = (
                f"% table '{name}' could not be generated: "
                f"{type(exc).__name__}: {exc}\n"
                "\\emph{This table could not be generated from the dataset.}\n")
    return out

def table_cost_model(data: dict) -> str:
    """The fitted cost model, one row per cipher and hardware-crypto level."""
    pts = data.get("e1", {}).get("points", [])
    if not pts:
        return "% e1 unavailable\n"
    rows = []
    for cipher in sorted({p["cipher"] for p in pts}):
        for hw in (True, False):
            if not any(p["cipher"] == cipher and bool(p["hw_crypto"]) == hw for p in pts):
                continue
            f = model.fit_from_points(pts, cipher, hw)
            if not f.ok:
                continue
            rows.append(
                f"{_tex_escape(cipher)} & {'yes' if hw else 'no'} & "
                f"{_fmt(f.a, 0)} & {_fmt(f.b, 3)} & "
                f"{_fmt(f.s_star, 0)} & "
                f"[{_fmt(f.s_star_ci[0], 0)}, {_fmt(f.s_star_ci[1], 0)}] & "
                f"{f.r_squared:.4f} \\\\")
    body = "\n".join(rows) if rows else "\\multicolumn{7}{c}{no stable fits} \\\\"
    return (
        "\\begin{tabular}{llrrrrr}\n\\toprule\n"
        "cipher & hw & $a$ (cyc) & $b$ (cyc/B) & $s^{*}$ (B) & 95\\% CI & $R^2$ \\\\\n"
        "\\midrule\n" + body + "\n\\bottomrule\n\\end{tabular}\n")


def table_iopath(data: dict) -> str:
    pts = [p for p in data.get("e3", {}).get("points", []) if p.get("ok")]
    if not pts:
        return "% e3 unavailable\n"
    payload = max(p["payload_bytes"] for p in pts)
    sel = [p for p in pts if p["payload_bytes"] == payload]
    rows = []
    for backend in sorted({p["backend"] for p in sel}):
        for p in sorted([q for q in sel if q["backend"] == backend],
                        key=lambda q: q["batch"]):
            rows.append(f"{_tex_escape(backend)} & {p['batch']} & "
                        f"{_fmt(p['cycles_median'], 0)} & "
                        f"{p['syscalls_per_packet']:.3f} & "
                        f"{_fmt(p['pps_median'], 0)} \\\\")
    return ("\\begin{tabular}{lrrrr}\n\\toprule\n"
            "backend & $B$ & cycles/pkt & syscalls/pkt & pkt/s \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def table_controls(data: dict) -> str:
    checks = data.get("controls", {}).get("checks", [])
    if not checks:
        return "% controls unavailable\n"
    rows = []
    for c in checks:
        verdict = "pass" if c.get("passed") else ("not run" if not c.get("ran") else "\\textbf{fail}")
        detail = c.get("outcome") or c.get("error") or ""
        rows.append(f"{_tex_escape(c['name'])} & {verdict} & "
                    f"\\footnotesize {_tex_escape(detail)} \\\\")
    return ("\\begin{tabular}{@{}p{0.30\\linewidth}lp{0.52\\linewidth}@{}}\n\\toprule\n"
            "control & verdict & outcome \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def table_environment(data: dict) -> str:
    env = data.get("environment", {})
    if not env:
        return "% environment unavailable\n"
    fields = [
        ("CPU", env.get("cpu_model", "")),
        ("architecture", env.get("arch", "")),
        ("physical cores", env.get("physical_cores", "")),
        ("SMT", "on" if env.get("smt_enabled") else "off"),
        ("kernel", env.get("os", "")),
        ("counter", f"{env.get('clock_source','')} at "
                    f"{env.get('tsc_hz',0)/1e9:.3f} GHz, "
                    f"{'invariant' if env.get('invariant_tsc') else 'not invariant'}"),
        ("governor", env.get("governor", "")),
        ("kernel isolation", ", ".join(
            [k for k, v in (("isolcpus", env.get("isolcpus")),
                            ("nohz\\_full", env.get("nohz_full")),
                            ("rcu\\_nocbs", env.get("rcu_nocbs"))) if v]) or "none"),
        ("interface", f"{env.get('nic_name','')} ({env.get('nic_driver','')})"),
        ("isolation tier", env.get("isolation_tier", "")),
        ("OpenSSL", env.get("openssl_version", "")),
        ("compiler", env.get("compiler", "")),
        ("flags", env.get("cxx_flags", "")),
        ("host class", env.get("host_class", "")),
    ]
    rows = [f"{k} & {_tex_escape(v)} \\\\" for k, v in fields]
    # The value column wraps: several of these are long strings (a CPU model, a
    # compiler flag list) and a fixed-width column would run off the page.
    return ("\\begin{tabular}{@{}lp{0.62\\linewidth}@{}}\n\\toprule\n"
            "property & value \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def table_virtualization(data: dict) -> str:
    tiers = [t for t in data.get("e7", {}).get("tiers", []) if t.get("ok")]
    if not tiers:
        return "% e7 unavailable\n"
    rows = [f"{_tex_escape(t['tier'])} & {_tex_escape(t.get('nic_driver',''))} & "
            f"{_fmt(t['cycles_median'], 0)} & {t.get('relative_to_host', 0):.3f} & "
            f"{t.get('syscalls_per_packet', 0):.3f} \\\\" for t in tiers]
    return ("\\begin{tabular}{llrrr}\n\\toprule\n"
            "tier & driver & cycles/pkt & vs.\\ host & syscalls/pkt \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def table_scaling(data: dict) -> str:
    pts = [p for p in data.get("e2", {}).get("points", []) if p.get("ok")]
    if not pts:
        return "% e2 unavailable\n"
    rows = [f"{p['shards']} & {p['strong_speedup']:.3f} & "
            f"{p['strong_efficiency']:.3f} & {p['weak_efficiency']:.3f} & "
            f"{_fmt(p['cycles_per_packet_strong'], 0)} \\\\"
            for p in sorted(pts, key=lambda q: q["shards"])]
    return ("\\begin{tabular}{rrrrr}\n\\toprule\n"
            "shards & strong speedup & strong eff. & weak eff. & cycles/pkt \\\\\n"
            "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def table_baselines(data: dict) -> str:
    e6 = data.get("e6", {})
    net = data.get("e6_network", {})
    rows = []
    for entry in e6.get("openssl_speed", []):
        if entry.get("ok"):
            rows.append(f"openssl speed, {_tex_escape(entry['cipher'])} & "
                        f"{entry['cycles_per_byte']:.4f} & one & bulk, no framing \\\\")
    for entry in e6.get("linerate", []):
        rows.append(f"linerate, {_tex_escape(entry['cipher'])} & "
                    f"{entry.get('cycles_per_byte_per_pass', 0):.4f} & two & "
                    f"decrypt and re-encrypt \\\\")
    for key, label in (("iperf3_gbps", "iperf3 over UDP, no crypto"),
                       ("wireguard_gbps", "WireGuard tunnel"),
                       ("linerate_gbps", "linerate over the same link")):
        if key in net:
            rows.append(f"{label} & \\multicolumn{{1}}{{c}}{{\\textemdash}} & "
                        f"\\multicolumn{{1}}{{c}}{{\\textemdash}} & "
                        f"{net[key]:.2f}\\,Gb/s on the wire \\\\")
    if not rows:
        return "% e6 unavailable\n"
    return ("\\begin{tabular}{lrll}\n\\toprule\n"
            "reference & cyc/B & passes & note \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


TABLES = {
    "cost_model": table_cost_model,
    "iopath": table_iopath,
    "controls": table_controls,
    "environment": table_environment,
    "virtualization": table_virtualization,
    "scaling": table_scaling,
    "baselines": table_baselines,
}



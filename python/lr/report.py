"""Turning the dataset into LaTeX.

The rule the project is built around: no number appears literally in the prose
of the report. Every quantity the text quotes is a macro defined here from
results.json, so a number in a sentence and the same number in a table cannot
disagree, and re-running the sweep updates the prose along with the figures.
tools/check_numbers.py enforces it by refusing to pass if a bare numeral turns
up in a sentence where a macro belongs.

Two things follow from that rule and are worth stating.

A macro whose data is missing must still be defined, or the report will not
compile at all — one absent experiment would take down the whole document. Every
macro therefore has a fallback that renders visibly, as an em dash with a
footnote-ready reason, rather than a zero that reads like a measurement.

Formatting belongs here, not in the text. Cycle counts are integers, per-byte
costs carry three decimals, ratios carry two, and a quantity that was measured
with an interval always prints with it. That way a reader never has to wonder
whether a bare number was rounded in the prose or in the data.
"""
from __future__ import annotations

import math
from typing import Any

from . import model

MISSING = r"\textemdash{}"

# LaTeX control sequences are letters only, so a cipher name cannot be turned
# into a macro name by mechanical transformation: "aes-256-gcm" would give
# \fitAAes256GcmHw, which TeX will not accept. The mapping is therefore
# explicit, with a fallback that spells out any digits in a name added later so
# a new cipher cannot silently produce an uncompilable document.
CIPHER_TAG = {
    "aes-256-gcm":          "AesGcm",
    "chacha20-poly1305":    "ChaPoly",
    "lr-aes-256-gcm":       "LrAesGcm",
    "lr-chacha20-poly1305": "LrChaPoly",
    "null":                 "Null",
}
_DIGIT_WORDS = ["Zero", "One", "Two", "Three", "Four",
                "Five", "Six", "Seven", "Eight", "Nine"]


def cipher_tag(name: str) -> str:
    if name in CIPHER_TAG:
        return CIPHER_TAG[name]
    out = []
    for word in name.replace("-", " ").replace("_", " ").split():
        piece = "".join(_DIGIT_WORDS[int(ch)] if ch.isdigit() else ch
                        for ch in word if ch.isalnum())
        out.append(piece[:1].upper() + piece[1:])
    return "".join(out) or "Unknown"


def _fmt(value: float | None, digits: int = 0, unit: str = "") -> str:
    if value is None or (isinstance(value, float) and not math.isfinite(value)):
        return MISSING
    if digits == 0:
        s = f"{value:,.0f}".replace(",", r"\,")
    else:
        s = f"{value:.{digits}f}"
    return s + (f"\\,{unit}" if unit else "")


def _pct(value: float | None, digits: int = 1) -> str:
    if value is None or not math.isfinite(value):
        return MISSING
    return f"{value * 100:.{digits}f}\\%"


def _tex_escape(s: str) -> str:
    out = []
    for ch in str(s):
        if ch in "#$%&_{}":
            out.append("\\" + ch)
        elif ch == "\\":
            out.append(r"\textbackslash{}")
        elif ch == "~":
            out.append(r"\textasciitilde{}")
        elif ch == "^":
            out.append(r"\textasciicircum{}")
        else:
            out.append(ch)
    return "".join(out)


class Macros:
    """Accumulates \\newcommand definitions and keeps their names unique."""

    def __init__(self) -> None:
        self._defs: dict[str, str] = {}

    def set(self, name: str, value: str) -> None:
        if name in self._defs and self._defs[name] != value:
            raise ValueError(f"macro {name} defined twice with different values")
        self._defs[name] = value

    def num(self, name: str, value: float | None, digits: int = 0, unit: str = "") -> None:
        self.set(name, _fmt(value, digits, unit))

    def pct(self, name: str, value: float | None, digits: int = 1) -> None:
        self.set(name, _pct(value, digits))

    def text(self, name: str, value: Any) -> None:
        self.set(name, _tex_escape(value))

    def render(self) -> str:
        lines = [
            "% Generated by python/lr/report.py from results/results.json.",
            "% Do not edit: every value here is derived from measured data, and",
            "% editing one would put the prose and the tables into disagreement.",
            "",
        ]
        for name in sorted(self._defs):
            lines.append(f"\\newcommand{{\\{name}}}{{{self._defs[name]}}}")
        return "\n".join(lines) + "\n"

    def names(self) -> list[str]:
        return sorted(self._defs)


